#!/usr/bin/env npx tsx
/**
 * Generate src/static/data.ts: static imports of every file under src/data.
 *
 * esbuild bundles JSON natively and text files via the text loader
 * (see scripts/build.mjs). Regenerate after re-running import_data / shop fact edits.
 *
 * Usage: npx tsx scripts/gen-data.ts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(ROOT, "src", "data");
const OUT = path.join(ROOT, "src", "static", "data.ts");

function varname(rel: string): string {
  const name = rel.replaceAll("/", "_").replaceAll(".", "_").replaceAll("-", "_");
  return name.replace(/[^0-9a-zA-Z_]/g, "_");
}

function jsonKey(s: string): string {
  return `"${s.replaceAll('"', '\\"')}"`;
}

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...walk(full));
    else if (ent.isFile()) out.push(full);
  }
  return out;
}

function main() {
  const files = walk(DATA).sort();
  const lines: string[] = [
    "// Generated by scripts/gen-data.ts — do not edit by hand.",
    "// Static shop content imported from src/data (copied from the",
    "// GitHub Pages shop files, host rewritten to this Worker).",
    "",
  ];
  const exports: { rel: string; v: string }[] = [];
  for (const f of files) {
    const relFromData = path.relative(DATA, f).split(path.sep).join("/");
    const v = varname(relFromData);
    // JSON stays as modules; other shop files use Vite/esbuild-compatible ?raw
    // so HonoX Vite build does not parse .html/.md as app HTML.
    const suffix = relFromData.endsWith(".json") ? "" : "?raw";
    lines.push(`import ${v} from "../data/${relFromData}${suffix}";`);
    exports.push({ rel: relFromData, v });
  }
  lines.push("");
  lines.push("export const DATA_FILES = {");
  for (const { rel, v } of exports) {
    lines.push(`  ${jsonKey(rel)}: ${v},`);
  }
  lines.push("};");
  lines.push("");
  lines.push("type DataFileValue = string | Record<string, unknown>;");
  lines.push("type DataFileKey = keyof typeof DATA_FILES;");
  lines.push("");
  lines.push("export function dataFile(rel: string): DataFileValue | undefined {");
  lines.push("  return DATA_FILES[rel as DataFileKey];");
  lines.push("}");
  lines.push("");

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, `${lines.join("\n")}\n`, "utf8");
  console.log(`wrote ${path.relative(ROOT, OUT)} with ${files.length} files`);
}

main();
