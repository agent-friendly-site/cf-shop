#!/usr/bin/env python3
"""Generate src/data.js: static imports of every file in src/data.

esbuild bundles JSON natively and text files via the text loader (see
scripts/build.mjs). Regenerate after re-running import_data.py.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src" / "data"


def varname(path):
    name = str(path.relative_to(DATA)).replace("/", "_").replace(".", "_").replace("-", "_")
    return re.sub(r"[^0-9a-zA-Z_]", "_", name)


def main():
    files = sorted(p for p in DATA.rglob("*") if p.is_file())
    lines = ["// Generated by scripts/gen_data_module.py — do not edit by hand.",
             "// Static shop content imported from src/data (copied from the",
             "// GitHub Pages shop files, host rewritten to this Worker).",
             ""]
    exports = {}
    for f in files:
        v = varname(f)
        rel = f.relative_to(ROOT / "src")
        lines.append(f'import {v} from "./{rel}";')
        exports[str(f.relative_to(DATA))] = v
    lines.append("")
    lines.append("export const DATA_FILES = {")
    for rel, v in exports.items():
        lines.append(f'  {json_key(rel)}: {v},')
    lines.append("};")
    lines.append("")
    lines.append("export function dataFile(rel) { return DATA_FILES[rel]; }")
    (ROOT / "src" / "data.js").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote src/data.js with {len(files)} files")


def json_key(s):
    return '"' + s.replace('"', '\\"') + '"'


if __name__ == "__main__":
    main()
